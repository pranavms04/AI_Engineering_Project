// Turns the two real data files into data/page-data.js for the page.
// Run from the build folder: node capture/build-data.mjs
// No values are typed by hand here: everything is copied from data/recorded.json
// (real RAGService answers) and data/eval.json (copied from evaluation/results).
import fs from "node:fs";

const recorded = JSON.parse(fs.readFileSync("data/recorded.json", "utf8"));
const evaluation = JSON.parse(fs.readFileSync("data/eval.json", "utf8"));

const pick = (a) => ({
  question: a.question,
  answer: a.answer,
  abstained: a.abstained,
  sources: a.sources.map((s, i) => ({
    citation: s.citation,
    source: s.source,
    page: s.page,
    score: s.score,
    text: a.retrieved_texts[i],
  })),
});

const data = {
  recording: {
    recorded_at: recorded.recorded_at,
    git_commit: recorded.git_commit,
    model: recorded.model,
    min_score: recorded.min_score,
    top_k: recorded.top_k,
    chunks_in_index: recorded.chunks_in_index,
  },
  answers: recorded.answers.map(pick),
  evaluation,
};

fs.writeFileSync(
  "data/page-data.js",
  "// Generated by capture/build-data.mjs from data/recorded.json and data/eval.json. Do not edit.\n" +
    `window.KA_DATA = ${JSON.stringify(data, null, 1)};\n`
);
console.log("answers:", data.answers.map((a) => a.question));
console.log("should-abstain scores:", evaluation.questions.filter((q) => q.should_abstain).map((q) => `${q.id} ${q.best_score} ${q.question}`));
